#!/usr/bin/env python3
"""
Write compact sibling tasks of a SkillsBench task: same domain and skill, but sized for a
27B terminal agent under a small token budget. Each sibling is a directory

    OUT/<name>/task.json        instruction, category, source, workdir
    OUT/<name>/gen_data.py      deterministic generator of the input files (run in the workdir)
    OUT/<name>/verifier/test_outputs.py   pytest that grades the workdir (reward 1 iff all pass)
    OUT/<name>/oracle/solve.sh  reference solution (never shipped to the agent)
    OUT/<name>/requirements.txt pip packages the task needs (subset of the image's set)

    NOTES_API_KEY=... make_sibling.py SRC_ROOT OUT [--only a,b] [--per-task 2] [--parallel 3]
"""

import argparse
import json
import os
import re
import sys
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from make_notes import collect_skills, frontmatter_body  # noqa: E402

LIBS = ("numpy pandas scipy sympy networkx openpyxl python-docx python-pptx pypdf reportlab matplotlib "
        "pillow lxml beautifulsoup4 pyyaml jinja2 pytest requests tabulate xlsxwriter markdown")

PROMPT = """You design training tasks for a small terminal agent (Qwen 27B). It works as root in a Linux container, in the directory /root/work, and acts through a JSON protocol with three actions: exec (one shell command), write_file (path, content), evaluate (ends the episode and grades). Its whole episode must fit in about 3000 output tokens and 8 tool calls, so a task has to be solvable by: inspect inputs with head/wc/python one-liners (2-3 calls), write ONE short script with write_file, run it, evaluate.

Below is a real benchmark task from the domain "{category}", with the skill documents its author shipped. Write {per_task} NEW sibling tasks that exercise the same skill and file formats but are much smaller: small inputs (every input file under 20 KB, generated by code), one clearly specified output file, a deterministic check. They must not be trivially solvable without doing the work (the answer must depend on the generated data), and they must be solvable by an expert in the allotted size. Vary the siblings: different sub-skill or output format, not the same task with new numbers.

Rules for each sibling:
- task.md: 120-250 words. State the inputs (paths under /root/work), exactly what to compute, the exact output path and format (field names, units, rounding), and any domain conventions needed. No hints about the implementation. Do not mention the grader.
- gen_data.py: Python 3.12, deterministic (random.seed / numpy seed fixed), writes the input files into the current directory (which will be /root/work). It may use only these packages: {libs}. It must NOT write the expected answer anywhere and must not leave the oracle's solution in the directory.
- verifier/test_outputs.py: pytest. It recomputes the expected answer from the input files in /root/work (the same formulas as the oracle, written independently; do not import gen_data), reads the agent's output file, and asserts equality within a stated tolerance. 3-6 tests, each a separate requirement (file exists, schema, values). Use only the packages above plus the standard library.
- oracle/solve.sh: bash; writes a Python script with a heredoc and runs it; produces the output from the inputs. It must pass the verifier.
- requirements.txt: the subset of the packages above that any of the files import, one per line (may be empty).
- name: lowercase-kebab, prefixed with "{source}-", unique across the siblings.

Reply with exactly one JSON object and nothing else, of the form
{{"siblings": [{{"name": "...", "files": {{"task.md": "...", "gen_data.py": "...", "verifier/test_outputs.py": "...", "oracle/solve.sh": "...", "requirements.txt": "..."}}}}]}}
Escape the file contents as JSON strings.

=== SOURCE TASK (task.md) ===
{task}

=== SOURCE SKILLS (digest) ===
{skills}

=== SOURCE VERIFIER (excerpt, for the grading style) ===
{verifier}
"""


def ask(base_url: str, key: str, model: str, prompt: str) -> str:
    if model.startswith("chatgpt/"):  # served through the Responses API only
        return ask_responses(base_url, key, model, prompt)
    body = {"model": model, "messages": [{"role": "user", "content": prompt}], "max_tokens": 24000, "temperature": 0.5}
    req = urllib.request.Request(base_url.rstrip("/") + "/chat/completions", data=json.dumps(body).encode(),
                                 headers={"Authorization": f"Bearer {key}", "Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=900) as r:
        choice = json.load(r)["choices"][0]
    if choice.get("finish_reason") == "length":
        raise ValueError("reply cut at max_tokens")
    content = choice["message"].get("content")
    if not content:
        raise ValueError(f"empty reply (finish_reason {choice.get('finish_reason')!r})")
    return content


def ask_responses(base_url: str, key: str, model: str, prompt: str) -> str:
    req = urllib.request.Request(base_url.rstrip("/") + "/responses", data=json.dumps({"model": model, "input": prompt}).encode(),
                                 headers={"Authorization": f"Bearer {key}", "Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=1800) as r:
        d = json.load(r)
    text = "".join(c.get("text", "") for o in d.get("output", []) if o.get("type") == "message"
                   for c in o.get("content", []) if c.get("type") == "output_text")
    if not text:
        raise ValueError(f"empty reply (status {d.get('status')!r})")
    return text


def parse_json(text: str) -> dict:
    text = text.strip()
    text = re.sub(r"^```(?:json)?\s*|\s*```$", "", text)
    dec = json.JSONDecoder()
    for i, ch in enumerate(text):
        if ch == "{":
            try:
                obj, _ = dec.raw_decode(text[i:])
                return obj
            except json.JSONDecodeError:
                continue
    raise ValueError("no JSON object in reply")


def category_of(task_md: str) -> str:
    m = re.search(r"^\s*category:\s*(\S+)", task_md, re.M)
    return m.group(1) if m else "unknown"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("src", type=Path)
    ap.add_argument("out", type=Path)
    ap.add_argument("--model", default="openrouter/anthropic/claude-opus-5.5")
    ap.add_argument("--base-url", default="https://infra.wenbo.io/litellm/v1")
    ap.add_argument("--parallel", type=int, default=3)
    ap.add_argument("--per-task", type=int, default=2)
    ap.add_argument("--only")
    ap.add_argument("--more", action="store_true",
                    help="add siblings even where some exist; the prompt lists the existing ones so the new ones differ")
    args = ap.parse_args()
    key = os.environ.get("NOTES_API_KEY")
    if not key:
        print("NOTES_API_KEY not set", file=sys.stderr)
        return 2
    args.out.mkdir(parents=True, exist_ok=True)
    tasks = sorted(d for d in args.src.iterdir() if (d / "task.md").is_file())
    if args.only:
        tasks = [t for t in tasks if t.name in args.only.split(",")]

    def job(d: Path) -> str:
        existing = sorted(p for p in args.out.glob(f"{d.name}-*") if (p / "task.json").is_file())
        if existing and not args.more:
            return f"{d.name}: exists"
        raw = (d / "task.md").read_text(encoding="utf-8")
        skills_dir = d / "environment" / "skills"
        skills = collect_skills(skills_dir, limit=30000) if skills_dir.is_dir() else "(none)"
        ver = d / "verifier" / "test_outputs.py"
        verifier = ver.read_text(encoding="utf-8", errors="replace")[:4000] if ver.is_file() else "(none)"
        prompt = PROMPT.format(category=category_of(raw), per_task=args.per_task, libs=LIBS, source=d.name,
                               task=frontmatter_body(raw)[:8000], skills=skills, verifier=verifier)
        if existing:
            prompt += "\n=== EXISTING SIBLINGS (write different ones: other sub-skills, outputs and names) ===\n" + "\n".join(
                f"- {p.name}: {json.loads((p / 'task.json').read_text())['instruction'][:300]}" for p in existing)
        reply = ""
        try:
            try:
                reply = ask(args.base_url, key, args.model, prompt)
            except ValueError:  # too long for one reply: one sibling at a time
                reply = ask(args.base_url, key, args.model, prompt.replace(f"Write {args.per_task} NEW sibling tasks", "Write 1 NEW sibling task"))
            obj = parse_json(reply)
            sibs = obj["siblings"]
        except Exception as exc:
            (args.out / f"{d.name}.failed.txt").write_text(repr(exc) + "\n\n" + (reply or ""))
            return f"{d.name}: FAILED {exc!r}"
        names = []
        for s in sibs:
            name = s["name"]
            if not name.startswith(d.name):
                name = f"{d.name}-{name}"
            sd = args.out / name
            if sd.exists():
                continue
            for rel, content in s["files"].items():
                p = sd / rel
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text(content.rstrip("\n") + "\n", encoding="utf-8")
            (sd / "task.json").write_text(json.dumps({
                "name": name, "source": d.name, "category": category_of(raw), "workdir": "/root/work",
                "instruction": s["files"]["task.md"].strip()}, indent=1, ensure_ascii=False) + "\n")
            names.append(name)
        return f"{d.name}: {', '.join(names)}"

    with ThreadPoolExecutor(args.parallel) as ex:
        for line in ex.map(job, tasks):
            print(line, flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
